#!/usr/bin/env node
'use strict';
/**
 * Embeds the wizard assets into vibey.js (between the "vibey-assets" markers):
 *
 * - small thumbnails (64×64, downscaled from content/dist/thumbnails) for the slot / type cards and templates
 * - a curated set of starter bundles from content/dist as templates (minified JSON), so the wizard works offline
 *
 *   node tools/embed-assets.js          # rewrites the block in vibey.js
 *   node tools/embed-assets.js --check  # exits 1 when the block is out of date (used by the unit tests)
 *
 * The starter set is original Vibe artwork (see NOTICE): it is only read here, never modified.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.resolve(ROOT, '..', 'content', 'dist');
const PLUGIN = path.join(ROOT, 'vibey.js');
const BEGIN = '/* <vibey-assets> generated by blockbench/tools/embed-assets.js from content/dist - do not edit by hand */';
const END = '/* </vibey-assets> */';
const THUMB = 64;

/** Card pictures: slot / type -> starter item whose thumbnail represents it. */
const CARD_THUMBS = {
	cosmetic: 'neon_wings', emote: 'wave',
	cape: 'vibe_cape', wings: 'neon_wings', aura: 'snowflake_orbit', pet: 'seal_buddy',
	shield: 'vibe_chevron_shield', hat: 'seal_beanie', back: 'seal_backpack',
};
/** Templates offered in step 4, per slot (cosmetics) and for emotes. Small, varied, all from the starter set. */
const TEMPLATES = {
	cape: ['vibe_cape', 'ice_floe_cape'],
	wings: ['neon_wings', 'crystal_wings'],
	aura: ['snowflake_orbit', 'ember_sparks'],
	pet: ['seal_buddy', 'pixel_penguin'],
	shield: ['vibe_chevron_shield', 'seal_crest_shield'],
	hat: ['seal_beanie', 'ice_crown'],
	back: ['seal_backpack'],
	emote: ['wave', 'vibe_dance', 'cheer'],
};

// ------------------------------------------------------------------ PNG
function crcTable() {
	const t = new Int32Array(256);
	for (let n = 0; n < 256; n++) {
		let c = n;
		for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
		t[n] = c;
	}
	return t;
}
const CRC = crcTable();
function crc32(buf) {
	let c = -1;
	for (let i = 0; i < buf.length; i++) c = CRC[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
	return (c ^ -1) >>> 0;
}
function chunk(type, data) {
	const len = Buffer.alloc(4);
	len.writeUInt32BE(data.length);
	const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
	const crc = Buffer.alloc(4);
	crc.writeUInt32BE(crc32(td));
	return Buffer.concat([len, td, crc]);
}
function decodePng(buf) {
	let pos = 8;
	let w, h, depth, ctype, interlace;
	const idat = [];
	let palette = null, trns = null;
	while (pos < buf.length) {
		const len = buf.readUInt32BE(pos);
		const type = buf.toString('ascii', pos + 4, pos + 8);
		const data = buf.subarray(pos + 8, pos + 8 + len);
		if (type === 'IHDR') {
			w = data.readUInt32BE(0);
			h = data.readUInt32BE(4);
			depth = data[8];
			ctype = data[9];
			interlace = data[12];
		} else if (type === 'PLTE') palette = data;
		else if (type === 'tRNS') trns = data;
		else if (type === 'IDAT') idat.push(data);
		pos += 12 + len;
	}
	if (depth !== 8 || interlace) throw new Error('only 8-bit non-interlaced PNGs are supported');
	const ch = { 6: 4, 2: 3, 0: 1, 4: 2, 3: 1 }[ctype];
	const raw = zlib.inflateSync(Buffer.concat(idat));
	const stride = w * ch;
	const out = Buffer.alloc(w * h * 4);
	let prev = Buffer.alloc(stride);
	for (let y = 0; y < h; y++) {
		const f = raw[y * (stride + 1)];
		const line = Buffer.from(raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1)));
		for (let i = 0; i < stride; i++) {
			const a = i >= ch ? line[i - ch] : 0;
			const b = prev[i];
			const c = i >= ch ? prev[i - ch] : 0;
			let v = line[i];
			if (f === 1) v += a;
			else if (f === 2) v += b;
			else if (f === 3) v += (a + b) >> 1;
			else if (f === 4) {
				const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
				v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
			}
			line[i] = v & 0xff;
		}
		for (let x = 0; x < w; x++) {
			const o = (y * w + x) * 4;
			const s = x * ch;
			if (ctype === 6) line.copy(out, o, s, s + 4);
			else if (ctype === 2) (out[o] = line[s]), (out[o + 1] = line[s + 1]), (out[o + 2] = line[s + 2]), (out[o + 3] = 255);
			else if (ctype === 0) (out[o] = out[o + 1] = out[o + 2] = line[s]), (out[o + 3] = 255);
			else if (ctype === 4) (out[o] = out[o + 1] = out[o + 2] = line[s]), (out[o + 3] = line[s + 1]);
			else if (ctype === 3) {
				const idx = line[s];
				out[o] = palette[idx * 3];
				out[o + 1] = palette[idx * 3 + 1];
				out[o + 2] = palette[idx * 3 + 2];
				out[o + 3] = trns && idx < trns.length ? trns[idx] : 255;
			}
		}
		prev = line;
	}
	return { width: w, height: h, data: out };
}
function encodePng(w, h, rgba) {
	const raw = Buffer.alloc((w * 4 + 1) * h);
	for (let y = 0; y < h; y++) {
		raw[y * (w * 4 + 1)] = 0;
		rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
	}
	const ihdr = Buffer.alloc(13);
	ihdr.writeUInt32BE(w, 0);
	ihdr.writeUInt32BE(h, 4);
	ihdr[8] = 8;
	ihdr[9] = 6;
	return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
/** Box filter downscale with premultiplied alpha (no dark fringes). */
function downscale(img, size) {
	const out = Buffer.alloc(size * size * 4);
	const fx = img.width / size, fy = img.height / size;
	for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
		let r = 0, g = 0, b = 0, a = 0, n = 0;
		for (let sy = Math.floor(y * fy); sy < Math.floor((y + 1) * fy); sy++) for (let sx = Math.floor(x * fx); sx < Math.floor((x + 1) * fx); sx++) {
			const o = (sy * img.width + sx) * 4;
			const al = img.data[o + 3];
			r += img.data[o] * al;
			g += img.data[o + 1] * al;
			b += img.data[o + 2] * al;
			a += al;
			n++;
		}
		const o = (y * size + x) * 4;
		if (a > 0) {
			out[o] = Math.round(r / a);
			out[o + 1] = Math.round(g / a);
			out[o + 2] = Math.round(b / a);
		}
		out[o + 3] = Math.round(a / n);
	}
	return out;
}
function thumb(name) {
	const img = decodePng(fs.readFileSync(path.join(DIST, 'thumbnails', name + '.png')));
	return encodePng(THUMB, THUMB, downscale(img, THUMB)).toString('base64');
}

// ------------------------------------------------------------------ build
function build() {
	const thumbs = {};
	const need = new Set(Object.values(CARD_THUMBS));
	Object.values(TEMPLATES).forEach((l) => l.forEach((n) => need.add(n)));
	[...need].sort().forEach((n) => (thumbs[n] = thumb(n)));
	const templates = {};
	for (const group of Object.keys(TEMPLATES)) {
		templates[group] = TEMPLATES[group].map((file) => {
			const bundle = JSON.parse(fs.readFileSync(path.join(DIST, file + '.vibey'), 'utf8'));
			return { key: file, name: bundle.name, bundle };
		});
	}
	const assets = { cards: CARD_THUMBS, thumbs, templates };
	const json = JSON.stringify(assets);
	return BEGIN + '\n\tconst ASSETS = ' + json + ';\n\t' + END;
}

function main() {
	const src = fs.readFileSync(PLUGIN, 'utf8');
	const a = src.indexOf(BEGIN);
	const b = src.indexOf(END);
	if (a < 0 || b < 0) throw new Error('markers not found in vibey.js');
	const block = build();
	const next = src.slice(0, a) + block + src.slice(b + END.length);
	if (process.argv.includes('--check')) {
		if (next !== src) {
			console.error('vibey.js assets are out of date: run node tools/embed-assets.js');
			process.exit(1);
		}
		console.log('assets up to date');
		return;
	}
	fs.writeFileSync(PLUGIN, next);
	console.log(`embedded ${block.length} bytes of assets into vibey.js`);
}

if (require.main === module) main();
module.exports = { decodePng, encodePng, downscale, build };
